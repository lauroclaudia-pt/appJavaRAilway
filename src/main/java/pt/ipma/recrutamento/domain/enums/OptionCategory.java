package pt.ipma.recrutamento.domain.enums;

/**
 * Categorias de listas de opções configuráveis pela Administração (campos tipo
 * "select" na definição da Vaga / Candidatura que variam ao longo do tempo por
 * razão legal ou organizacional, em vez de estarem fixas em código).
 */
public enum OptionCategory {
    VINCULO,
    REGIME,
    NIVEL_HABILITACIONAL,
    SITUACAO_PROFISSIONAL,
    RELACAO_VAGAS_CANDIDATURAS,
    CARGO_CARREIRA
}
